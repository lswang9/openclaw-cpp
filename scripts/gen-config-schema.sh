#!/usr/bin/env bash
# Regenerate src/config/upstream_schema.inc from upstream's runtime-computed base config schema
# (computeBaseConfigSchemaResponse). Needs Node >= 24 + pnpm 12 and an upstream checkout with deps:
#   git -C $UP worktree add --detach /tmp/upschema && cd /tmp/upschema && pnpm install --frozen-lockfile --ignore-scripts
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
UPS="${UPSCHEMA:-/tmp/upschema}"
cat > /tmp/dump-schema.ts <<E
import { computeBaseConfigSchemaResponse } from "$UPS/src/config/schema-base.js";
import { writeFileSync } from "node:fs";
writeFileSync("/tmp/upstream-config-schema.json", JSON.stringify(computeBaseConfigSchemaResponse({ generatedAt: "2026-10-05T00:00:00.000Z" })));
E
(cd "$UPS" && node --import tsx /tmp/dump-schema.ts)
python3 - "$ROOT/src/config/upstream_schema.inc" <<'P'
import json, sys
s = json.dumps(json.load(open('/tmp/upstream-config-schema.json')), separators=(',', ':'), ensure_ascii=False)
chunks = [s[i:i+16000] for i in range(0, len(s), 16000)]
with open(sys.argv[1], 'w') as f:
    f.write('// Generated by scripts/gen-config-schema.sh from upstream computeBaseConfigSchemaResponse(). Do not edit.\n')
    for c in chunks:
        assert ')OCS"' not in c
        f.write('R"OCS(' + c + ')OCS"\n')
print(len(s), 'bytes,', len(chunks), 'chunks')
P
