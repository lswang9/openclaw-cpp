#!/usr/bin/env python3
"""Probe every upstream v2026.10.5 gateway method against a running gateway with {} params and list the ones that
answer 'not implemented in the C++ runtime'. --write regenerates src/gateway/unimplemented_generated.inc;
--check fails when the generated list is stale (a method became real, or a new one is unimplemented)."""
import json, os, re, sys, urllib.request
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
url, mode = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else "--print")
names = [l.strip() for l in open(os.path.join(ROOT, "scripts/upstream-methods.txt")) if l.strip()]
un = []
for m in names:
    if "restart" in m or "shutdown" in m or m.startswith("update.") or m in ("gateway.stop", "gateway.stop.request", "config.reload"): continue
    req = urllib.request.Request(url, json.dumps({"jsonrpc": "2.0", "id": 1, "method": m, "params": {}}).encode(), {"Content-Type": "application/json"})
    try: body = urllib.request.urlopen(req, timeout=10).read()
    except urllib.error.HTTPError as e: body = e.read()
    if b"not implemented in the C++ runtime" in body: un.append(m)
inc = os.path.join(ROOT, "src/gateway/unimplemented_generated.inc")
text = "// Generated by scripts/probe-unimplemented.py: upstream v2026.10.5 methods that answer\n// \"not implemented in the C++ runtime\" (excluded from the implemented count).\n" + "".join(f'    "{m}",\n' for m in un)
if mode == "--write": open(inc, "w").write(text); print(f"{len(un)} unimplemented of {len(names)}")
elif mode == "--check":
    cur = re.findall(r'"([^"]+)"', open(inc).read().split("\n", 2)[2])
    if cur != un:
        print("stale unimplemented list: became real:", sorted(set(cur) - set(un)), "newly unimplemented:", sorted(set(un) - set(cur))); sys.exit(1)
    print(f"unimplemented list current: {len(un)} of {len(names)} upstream methods")
else: print("\n".join(un))
